# FORMAT CVE INFORMATION
# ==========================================================

def format_cves(article):
    """
    Create HTML for CVE information.
    """

    cves = get_article_cves(
        article
    )


    if not cves:

        return """
        <div
            style="
                background:#f8f9fa;
                border:1px solid #dee2e6;
                padding:12px;
                border-radius:5px;
            "
        >

            <em>No CVE detected.</em>

        </div>
        """


    cve_html = """

    <div
        style="
            background:#f8f9fa;
            border:1px solid #dee2e6;
            padding:12px;
            border-radius:5px;
        "
    >

    <ul
        style="
            margin:0;
            padding-left:20px;
        "
    >

    """


    for cve in cves:

        # --------------------------------------------------
        # CVE stored as dictionary
        # --------------------------------------------------

        if isinstance(
            cve,
            dict
        ):

            cve_id = cve.get(
                "cve_id",
                cve.get(
                    "id",
                    "Unknown CVE"
                )
            )


            cvss = cve.get(
                "cvss_score"
            )


            cve_severity = cve.get(
                "severity"
            )


            description = cve.get(
                "description"
            )


        # --------------------------------------------------
        # CVE stored as string
        # --------------------------------------------------

        else:

            cve_id = cve

            cvss = None

            cve_severity = None

            description = None


        cve_html += (
            "<li style='margin-bottom:8px;'>"
            "<strong>"
            + html.escape(
                str(cve_id)
            )
            + "</strong>"
        )


        if cvss:

            cve_html += (
                f"<br>"
                f"<small>"
                f"CVSS Score: "
                f"{html.escape(str(cvss))}"
                f"</small>"
            )


        if cve_severity:

            cve_html += (
                f"<br>"
                f"<small>"
                f"CVE Severity: "
                f"{html.escape(str(cve_severity))}"
                f"</small>"
            )


        if description:

            cve_html += (
                f"<br>"
                f"<small>"
                f"{html.escape(str(description))}"
                f"</small>"
            )


        cve_html += "</li>"


    cve_html += """

    </ul>

    </div>

    """


    return cve_html


