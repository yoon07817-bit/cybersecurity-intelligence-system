# GET ARTICLE CVES
# ==========================================================

def get_article_cves(article):
    """
    Get CVE identifiers from the article dictionary.

    Supported fields:
        cves
        cve_ids
        cve

    CVE information can be:
        - list of strings
        - a single string
        - list of dictionaries
    """

    cves = []


    # ------------------------------------------------------
    # Preferred field
    # ------------------------------------------------------

    if article.get("cves"):

        cves = article["cves"]


    # ------------------------------------------------------
    # Alternative field
    # ------------------------------------------------------

    elif article.get("cve_ids"):

        cves = article["cve_ids"]


    # ------------------------------------------------------
    # Single CVE field
    # ------------------------------------------------------

    elif article.get("cve"):

        cves = article["cve"]


    # ------------------------------------------------------
    # Convert single string to list
    # ------------------------------------------------------

    if isinstance(cves, str):

        cves = [cves]


    # ------------------------------------------------------
    # Ensure list
    # ------------------------------------------------------

    if not isinstance(cves, list):

        cves = [cves]


    return cves


