# CLEAN SUMMARY FOR EMAIL
# ==========================================================

def clean_summary(summary):
    """
    Convert the Markdown summary generated by the AI
    into simple HTML suitable for email.
    """

    if not summary:
        return "<p>No summary available.</p>"


    summary = str(summary)

    # Escape HTML characters first
    summary = html.escape(summary)


    # Convert Markdown headings

    summary = re.sub(
        r"##\s*\*\*(.*?)\*\*",
        r"<h4>\1</h4>",
        summary
    )


    # Convert bold Markdown

    summary = re.sub(
        r"\*\*(.*?)\*\*",
        r"<strong>\1</strong>",
        summary
    )


    # Process lines

    lines = summary.split("\n")

    output = []

    in_list = False


    for line in lines:

        line = line.strip()


        # --------------------------------------------------
        # Bullet point
        # --------------------------------------------------

        if line.startswith("- "):

            if not in_list:

                output.append("<ul>")

                in_list = True


            output.append(
                f"<li>{line[2:]}</li>"
            )


        else:

            if in_list:

                output.append(
                    "</ul>"
                )

                in_list = False


            if line:

                # Don't wrap HTML headings in <p>
                if (
                    line.startswith("<h4>")
                    and line.endswith("</h4>")
                ):

                    output.append(
                        line
                    )

                else:

                    output.append(
                        f"<p>{line}</p>"
                    )


    if in_list:

        output.append(
            "</ul>"
        )


    return "\n".join(output)


