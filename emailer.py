# GET RECOMMENDATION
# ==========================================================

def get_article_recommendation(article):
    """
    Get the protection recommendation already generated
    for the article.

    A fallback recommendation is used if the article does
    not contain one.
    """

    recommendation = article.get(
        "recommendation"
    )


    if not recommendation:

        recommendation = (
            "Review the affected systems, "
            "apply available security updates, "
            "monitor for suspicious activity, "
            "review access controls, and follow "
            "appropriate cybersecurity best practices."
        )


    return recommendation


# ==========================================================
# SEVERITY STYLE
# ==========================================================

def get_severity_style(severity):

    severity = str(
        severity
    ).lower()


    if severity == "critical":

        return (
            "color:#dc3545;"
            "font-weight:bold;"
        )


    elif severity == "high":

        return (
            "color:#fd7e14;"
            "font-weight:bold;"
        )


    elif severity == "medium":

        return (
            "color:#b8860b;"
            "font-weight:bold;"
        )


    else:

        return (
            "color:#198754;"
            "font-weight:bold;"
        )


